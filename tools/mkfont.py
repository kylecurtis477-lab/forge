#!/usr/bin/env python3
"""Render ASCII 32..126 of DejaVu Sans Mono (Bitstream Vera license) into an 8x16 1-bpp bitmap font
and write it as a Forge include (u8[1536] global, 16 bytes per glyph, MSB = leftmost pixel).
usage: mkfont.py font.ttf out.fsi"""
import sys
from PIL import Image, ImageDraw, ImageFont
ttf, out = sys.argv[1], sys.argv[2]
f = ImageFont.truetype(ttf, 13)
rows = []
for c in range(32, 127):
    im = Image.new('L', (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), chr(c), font=f, fill=255)
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) >= 110:
                b |= 0x80 >> x
        rows.append(b)
with open(out, 'w') as o:
    o.write('# 8x16 bitmap font, ASCII 32..126, generated by tools/mkfont.py from DejaVu Sans Mono\n')
    o.write('# (Bitstream Vera Fonts license, DejaVu changes public domain). Glyph g at font8x16[(g-32)*16].\n')
    o.write('font8x16: u8[1520] = [')
    o.write(', '.join(str(b) for b in rows))
    o.write(']\n')
# print preview
for c in 'Fg':
    i = (ord(c) - 32) * 16
    for y in range(16):
        print(''.join('#' if rows[i + y] & (0x80 >> x) else '.' for x in range(8)))
