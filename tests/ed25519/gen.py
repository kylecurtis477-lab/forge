#!/usr/bin/env python3
# Generate tests/ed25519 vectors: signatures from `cryptography` (independent of tools/ed25519.py),
# plus corrupted ones; emits a Forge program that verifies each and prints 1/0 per vector.
import os, sys
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization as S
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'tools'))
import ed25519 as mine
L = 2**252 + 27742317777372353535851937790883648493
vec = []  # (pk, sig, msg, expect)
for k in range(6):
    seed = bytes((k * 37 + i) & 255 for i in range(32))
    sk = Ed25519PrivateKey.from_private_bytes(seed)
    pk = sk.public_key().public_bytes(S.Encoding.Raw, S.PublicFormat.Raw)
    n = [0, 1, 31, 64, 95, 96][k]
    m = bytes((k * 11 + i * 7) & 255 for i in range(n))
    sig = sk.sign(m)
    assert mine.sign(seed, m) == sig
    vec.append((pk, sig, m, 1))
    if k == 1:
        vec.append((pk, sig[:5] + bytes([sig[5] ^ 1]) + sig[6:], m, 0))       # R flipped
        vec.append((pk, sig[:40] + bytes([sig[40] ^ 4]) + sig[41:], m, 0))    # S flipped
    if k == 3:
        vec.append((pk, sig, bytes([m[0] ^ 1]) + m[1:], 0))                    # message flipped
        s = int.from_bytes(sig[32:], 'little') + L                             # non-canonical S
        vec.append((pk, sig[:32] + s.to_bytes(32, 'little'), m, 0))
        other = Ed25519PrivateKey.from_private_bytes(bytes(32)).public_key().public_bytes(S.Encoding.Raw, S.PublicFormat.Raw)
        vec.append((other, sig, m, 0))                                         # wrong key
        vec.append((bytes([2]) + bytes(31), sig, m, 0))                        # not a curve point (y=2)
def arr(name, b, n):
    b = b + bytes(n - len(b))
    return "%s: u8[%d] = [%s]\n" % (name, n, ", ".join(str(x) for x in b))
out = ['# forge: safe\n# forge: no-runtime\n# generated by tests/ed25519/gen.py\ninclude "../../examples/user/ulib.fsi"\ninclude "../../examples/kernel/ed25519.fsi"\n']
for i, (pk, sig, m, e) in enumerate(vec):
    out.append(arr("pk%d" % i, pk, 32) + arr("sg%d" % i, sig, 64) + arr("ms%d" % i, m, 96))
out.append('''
pkb: B32
sgb: EdSig
msb: EdMsg
''')
for i, (pk, sig, m, e) in enumerate(vec):
    out.append('''
def setv%d():
    i: u64 = 0
    while i < 32:
        pkb.b[i] = pk%d[i]
        sgb.r.b[i] = sg%d[i]
        sgb.s.b[i] = sg%d[i + 32]
        i += 1
    i = 0
    while i < 96:
        msb.b[i] = ms%d[i]
        i += 1
''' % (i, i, i, i, i))
out.append('\n@export\ndef _start():\n')
for i, (pk, sig, m, e) in enumerate(vec):
    out.append('    setv%d()\n    out_u64(ed25519_verify(addr(sgb), addr(pkb), addr(msb), %d))\n' % (i, len(m)))
out.append('    out("\\n")\n    flush()\n    sys_exit(0)\n')
open(sys.argv[1], 'w').write(''.join(out))
print(''.join(str(e) for *_, e in vec))
